import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist');
const syncUrl = String(process.env.BC_SYNC_URL || '').replace(/\/$/, '');
let parsedSyncUrl;
try { parsedSyncUrl = new URL(syncUrl); } catch {}
const localHost = parsedSyncUrl && ['127.0.0.1', 'localhost'].includes(parsedSyncUrl.hostname);
if (!parsedSyncUrl || (parsedSyncUrl.protocol !== 'https:' && !localHost)) {
  throw new Error('BC_SYNC_URL must be an HTTPS Worker URL (or localhost for testing).');
}

const files = [
  'index.html',
  'moderator.html',
  'board.html',
  'board.js',
  'cards.js',
  'styles.css',
  'sync.js'
];

fs.rmSync(output, {recursive: true, force: true});
fs.mkdirSync(output, {recursive: true});
for (const file of files) fs.copyFileSync(path.join(root, file), path.join(output, file));
fs.writeFileSync(
  path.join(output, 'config.js'),
  `// Generated by scripts/build-pages.mjs\nwindow.BC_SYNC_URL = ${JSON.stringify(syncUrl)};\n`
);
fs.writeFileSync(path.join(output, '.nojekyll'), '');
console.log(`Built GitHub Pages site in ${output} using ${syncUrl}`);
